#!/usr/bin/env python3
"""
01_mutant_coverage.py
=====================
Mutant Reachability / Rule Coverage Analysis
--------------------------------------------
For each survived mutant, check whether the source models generated by LLMs
actually exercise (cover) the ATL rule / binding / helper where the mutation
was injected.

Coverage definition used here
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
A mutant's location is *covered* by a test t iff the trace file produced by
running t on the **original** transformation contains at least one TraceLink
whose Rule name matches the mutant's injected rule.

Outputs (per dataset, per model/config combination)
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
  results_v2/analysis/coverage/
    {dataset}_coverage_summary.csv      – per-mutant status
    {dataset}_coverage_aggregate.json   – aggregate counts
    coverage_overall.csv                – cross-dataset summary table

Usage
~~~~~
  python 01_mutant_coverage.py [--base BASE_DIR] [--datasets d1 d2 ...]

Defaults
~~~~~~~~
  BASE_DIR = ~/research/llm_mt_experiment
  DATASETS = BibTeX2DocBook CPL2SPL UML2ER Ecore2Maude
"""

import argparse
import csv
import json
import os
import re
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

# ──────────────────────────────────────────────────────────────────────────────
# Configuration
# ──────────────────────────────────────────────────────────────────────────────

DEFAULT_BASE    = Path.home() / "research" / "llm_mt_experiment"
DATASETS        = ["BibTeX2DocBook", "CPL2SPL", "UML2ER", "Ecore2Maude"]
MODELS          = ["deepseek", "qwen", "gpt"]

# Regex to extract MutantN index from filename like:
#   output_0001_BibTeX2DocBook_Mutant3_trace.xmi
MUTANT_FILE_RE  = re.compile(
    r"output_(?P<tid>\d+)_(?P<dataset>.+?)_Mutant(?P<mid>\d+)_trace\.xmi$",
    re.IGNORECASE,
)
ORIG_FILE_RE    = re.compile(
    r"output_(?P<tid>\d+)_trace\.xmi$",
    re.IGNORECASE,
)

# ──────────────────────────────────────────────────────────────────────────────
# ATL mutation operators we recognise (populated by parse_atl_mutants)
# ──────────────────────────────────────────────────────────────────────────────
MUTATION_OPS = {
    "RD":  "rule_deletion",
    "BFC": "binding_feature_change",
    "BVC": "binding_value_change",
    "GM":  "guard_mutation",
    "NM":  "navigation_mutation",
    "HEM": "helper_expression_mutation",
}


# ──────────────────────────────────────────────────────────────────────────────
# Helpers – ATL parsing
# ──────────────────────────────────────────────────────────────────────────────

def _atl_rule_names(atl_path: Path) -> set[str]:
    """Return set of rule/helper names declared in an ATL file (text scan)."""
    names: set[str] = set()
    if not atl_path.exists():
        return names
    text = atl_path.read_text(errors="replace")
    # Match:  rule RuleName  |  lazy rule RuleName  |  helper context ... def : name
    for m in re.finditer(
        r"(?:(?:lazy\s+)?rule|helper(?:\s+context\s+\S+)?\s+def\s*:)\s+(\w+)",
        text,
    ):
        names.add(m.group(1))
    return names


def parse_atl_mutants(atl_dir: Path) -> dict[int, dict]:
    """
    Scan the ATL directory for mutant files and return a dict
      { mutant_id: { "rule": str, "op": str, "op_label": str } }

    File naming conventions tried (common in MuATL / AMW tooling):
      Mutant_1.atl  /  mutant1.atl  /  Mutant1_RD.atl  /  original_Mutant1.atl
    """
    mutants: dict[int, dict] = {}
    if not atl_dir.exists():
        return mutants

    for atl_file in sorted(atl_dir.glob("**/*.atl")):
        fname = atl_file.stem  # filename without extension

        # Skip original / non-mutant files
        if fname.lower() in {"original", "base", "source"}:
            continue

        # Extract mutant index
        id_match = re.search(r"[Mm]utant_?(\d+)", fname)
        if not id_match:
            continue
        mid = int(id_match.group(1))

        # Extract operator token if present in filename (e.g., Mutant3_BVC.atl)
        op_token = None
        for key in MUTATION_OPS:
            if key in fname.upper():
                op_token = key
                break

        # Determine which rule(s) differ from original by scanning rule names
        # (cheap heuristic: the mutant file lists the rules it touches)
        rule_names = _atl_rule_names(atl_file)

        mutants[mid] = {
            "rule":     next(iter(rule_names), "unknown"),
            "all_rules": sorted(rule_names),
            "op":       op_token or "UNKNOWN",
            "op_label": MUTATION_OPS.get(op_token, "unknown_operator"),
            "atl_file": str(atl_file),
        }

    return mutants


# ──────────────────────────────────────────────────────────────────────────────
# Helpers – trace XMI parsing
# ──────────────────────────────────────────────────────────────────────────────

# XMI namespace variants used by ATL/Trace
_NS = [
    "{http://www.eclipse.org/atl/2004/traceModel}",
    "{http://www.eclipse.org/atl/2006/ATL-Operations}",
    "",  # no namespace
]

def _extract_executed_rules(xmi_path: Path) -> set[str]:
    """
    Return the set of ATL rule names that appear in a trace XMI.
    We look for elements whose tag or attribute 'rule' contains a rule name.
    Robust to slight namespace differences.
    """
    executed: set[str] = set()
    if not xmi_path.exists():
        return executed
    try:
        tree = ET.parse(xmi_path)
        root = tree.getroot()
    except ET.ParseError:
        return executed

    # Common patterns in ATL trace XMIs:
    #   <traceLink rule="RuleName" ...>
    #   <TraceLink rule="RuleName" ...>
    #   <oclrule name="RuleName" ...>
    for elem in root.iter():
        tag = elem.tag.split("}")[-1].lower()  # strip namespace
        # attribute "rule" or "name" on tracelink / rule elements
        if "tracelink" in tag or "rule" in tag:
            for attr in ("rule", "name", "ruleName"):
                val = elem.get(attr)
                if val:
                    executed.add(val)
        # Also check text content for short rule references
        if elem.text and re.match(r"^\w+$", (elem.text or "").strip()):
            executed.add(elem.text.strip())

    return executed


# ──────────────────────────────────────────────────────────────────────────────
# Kill / survive status from existing SBFL results
# ──────────────────────────────────────────────────────────────────────────────

def load_kill_status(results_v2: Path, dataset: str) -> dict[int, str]:
    """
    Attempt to load pre-computed kill status from export_sbfl_detailed output.
    Returns {mutant_id: "killed" | "survived" | "compile_failed" | "stillborn"}.

    We look for:
      results_v2/*/outputs/{dataset}/*/sbfl_detailed*.csv
      results_v2/analysis/sbfl/{dataset}*.csv
    Fallback: infer from presence/absence of mutant trace files.
    """
    status: dict[int, str] = {}

    patterns = [
        results_v2 / "analysis" / "sbfl" / f"{dataset}*.csv",
        results_v2 / "**" / "outputs" / dataset / "**" / "sbfl_detailed*.csv",
    ]
    import glob as _glob
    for pat in patterns:
        for fp in _glob.glob(str(pat), recursive=True):
            try:
                with open(fp, newline="", encoding="utf-8") as f:
                    reader = csv.DictReader(f)
                    for row in reader:
                        mid_raw  = row.get("mutant_id") or row.get("MutantID") or row.get("mutant")
                        stat_raw = row.get("status") or row.get("Status") or row.get("kill_status")
                        if mid_raw and stat_raw:
                            try:
                                status[int(mid_raw)] = stat_raw.strip().lower()
                            except ValueError:
                                pass
            except Exception:
                pass

    return status


# ──────────────────────────────────────────────────────────────────────────────
# Core analysis
# ──────────────────────────────────────────────────────────────────────────────

def analyse_dataset(
    base: Path,
    dataset: str,
    results_v2: Path,
) -> dict:
    """
    Run full coverage analysis for one dataset.
    Returns a dict with aggregate stats and per-mutant rows.
    """
    atl_dir = base / "datasets" / f"models_{dataset}" / "transformations"
    mutant_info = parse_atl_mutants(atl_dir)

    # ── Collect all original trace files (union over all models/configs) ──────
    # Mapping: test_id -> set of executed rules (from original traces)
    test_rule_coverage: dict[str, set[str]] = defaultdict(set)

    for model in MODELS:
        out_root = results_v2 / model / "outputs" / dataset
        if not out_root.exists():
            continue
        for config_dir in sorted(out_root.iterdir()):
            if not config_dir.is_dir():
                continue
            for xmi in config_dir.glob("output_*_trace.xmi"):
                m = ORIG_FILE_RE.match(xmi.name)
                if not m:
                    continue
                tid = m.group("tid")
                rules = _extract_executed_rules(xmi)
                test_rule_coverage[tid].update(rules)

    # Union of all rules ever executed across the entire test pool
    all_executed_rules: set[str] = set()
    for rules in test_rule_coverage.values():
        all_executed_rules.update(rules)

    # ── Collect killed / survived mutants ──────────────────────────────────
    # First try pre-computed status CSV
    kill_status = load_kill_status(results_v2, dataset)

    # If empty, infer: a mutant is "killed" if its trace differs from original
    # in at least one config (crude proxy – real kill needs output comparison).
    # We rely on SBFL script output; if unavailable, we just mark "unknown".
    if not kill_status:
        print(f"  [WARN] No pre-computed kill status found for {dataset}. "
              "Marking all runnable mutants as 'unknown'.")

    # ── Build per-mutant rows ──────────────────────────────────────────────
    rows = []
    counters = defaultdict(int)

    # Gather unique mutant IDs from trace files
    mutant_ids_seen: set[int] = set()
    for model in MODELS:
        out_root = results_v2 / model / "outputs" / dataset
        if not out_root.exists():
            continue
        for config_dir in sorted(out_root.iterdir()):
            if not config_dir.is_dir():
                continue
            for xmi in config_dir.glob(f"output_*_{dataset}_Mutant*_trace.xmi"):
                m = MUTANT_FILE_RE.match(xmi.name)
                if m:
                    mutant_ids_seen.add(int(m.group("mid")))

    # Also add from pre-computed kill status
    mutant_ids_seen.update(kill_status.keys())
    # And from ATL parse
    mutant_ids_seen.update(mutant_info.keys())

    for mid in sorted(mutant_ids_seen):
        info     = mutant_info.get(mid, {})
        mut_rule = info.get("rule", "unknown")
        op_label = info.get("op_label", "unknown_operator")
        raw_stat = kill_status.get(mid, "unknown").lower()

        # Normalise status
        if raw_stat in {"killed", "kill"}:
            status = "killed"
        elif raw_stat in {"survived", "alive", "survive"}:
            status = "survived"
        elif raw_stat in {"compile_failed", "compile_error", "compileerror"}:
            status = "compile_failed"
        elif raw_stat in {"stillborn"}:
            status = "stillborn"
        else:
            # Try to infer: if mutant trace files exist it was runnable
            has_trace = any(
                (results_v2 / mdl / "outputs" / dataset).exists()
                for mdl in MODELS
            )
            status = "unknown_runnable" if has_trace else "unknown"

        # Coverage check – only meaningful for survived / unknown_runnable
        if status in {"survived", "unknown_runnable", "unknown"}:
            covered = (mut_rule != "unknown") and (mut_rule in all_executed_rules)
        else:
            covered = None  # not applicable

        # Classify
        if status == "killed":
            classification = "killed"
            counters["killed"] += 1
        elif status == "compile_failed":
            classification = "compile_failed"
            counters["compile_failed"] += 1
        elif status == "stillborn":
            classification = "stillborn"
            counters["stillborn"] += 1
        elif status in {"survived", "unknown_runnable"}:
            if covered is True:
                classification = "survived_covered"
                counters["survived_covered"] += 1
            elif covered is False:
                classification = "survived_uncovered"
                counters["survived_uncovered"] += 1
            else:
                classification = "survived_unknown_coverage"
                counters["survived_unknown_coverage"] += 1
        else:
            classification = "unknown"
            counters["unknown"] += 1

        counters["total"] += 1

        rows.append({
            "dataset":        dataset,
            "mutant_id":      mid,
            "mutated_rule":   mut_rule,
            "mutation_op":    op_label,
            "kill_status":    status,
            "location_covered": ("yes" if covered else ("no" if covered is False else "n/a")),
            "classification": classification,
        })

    # ── Aggregate stats ───────────────────────────────────────────────────
    survived_total   = counters["survived_covered"] + counters["survived_uncovered"] + counters["survived_unknown_coverage"]
    runnable         = counters["killed"] + survived_total
    cov_rate         = (
        counters["survived_covered"] / survived_total
        if survived_total > 0 else 0.0
    )

    aggregate = {
        "dataset":                          dataset,
        "total_mutants_seen":               counters["total"],
        "compile_failed":                   counters["compile_failed"],
        "stillborn":                        counters["stillborn"],
        "runnable_mutants":                 runnable,
        "killed":                           counters["killed"],
        "survived_total":                   survived_total,
        "survived_uncovered":               counters["survived_uncovered"],
        "survived_covered":                 counters["survived_covered"],
        "survived_unknown_coverage":        counters["survived_unknown_coverage"],
        "coverage_rate_of_mutant_locations": round(cov_rate, 4),
        "mutation_score_all":               round(counters["killed"] / runnable, 4) if runnable > 0 else 0.0,
    }

    return {"aggregate": aggregate, "rows": rows}


# ──────────────────────────────────────────────────────────────────────────────
# Output
# ──────────────────────────────────────────────────────────────────────────────

def write_outputs(base: Path, results_v2: Path, all_results: dict):
    out_dir = results_v2 / "analysis" / "coverage"
    out_dir.mkdir(parents=True, exist_ok=True)

    row_fields = [
        "dataset", "mutant_id", "mutated_rule", "mutation_op",
        "kill_status", "location_covered", "classification",
    ]
    agg_rows = []

    for dataset, result in all_results.items():
        # Per-dataset detailed CSV
        detail_path = out_dir / f"{dataset}_coverage_summary.csv"
        with open(detail_path, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=row_fields)
            w.writeheader()
            w.writerows(result["rows"])
        print(f"  Wrote {detail_path}")

        # Per-dataset JSON aggregate
        agg_path = out_dir / f"{dataset}_coverage_aggregate.json"
        with open(agg_path, "w", encoding="utf-8") as f:
            json.dump(result["aggregate"], f, indent=2)
        print(f"  Wrote {agg_path}")

        agg_rows.append(result["aggregate"])

    # Overall summary table
    if agg_rows:
        overall_path = out_dir / "coverage_overall.csv"
        with open(overall_path, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(agg_rows[0].keys()))
            w.writeheader()
            w.writerows(agg_rows)
        print(f"  Wrote {overall_path}")

    # Pretty-print to stdout
    print("\n" + "=" * 72)
    print("COVERAGE ANALYSIS  –  SUMMARY")
    print("=" * 72)
    header = f"{'Dataset':<20} {'Run':>6} {'Kill':>6} {'Surv':>6} {'Uncov':>7} {'Cov':>7} {'MS':>8}"
    print(header)
    print("-" * 72)
    for a in agg_rows:
        print(
            f"{a['dataset']:<20} "
            f"{a['runnable_mutants']:>6} "
            f"{a['killed']:>6} "
            f"{a['survived_total']:>6} "
            f"{a['survived_uncovered']:>7} "
            f"{a['survived_covered']:>7} "
            f"{a['mutation_score_all']:>8.3f}"
        )
    print("=" * 72)
    print("Uncov = survived but mutant location NOT covered")
    print("Cov   = survived and mutant location WAS covered")
    print("MS    = killed / runnable  (incl. all survived)")


# ──────────────────────────────────────────────────────────────────────────────
# Entry point
# ──────────────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="Mutant reachability / rule coverage analysis")
    parser.add_argument("--base", default=str(DEFAULT_BASE), help="Project root")
    parser.add_argument("--datasets", nargs="+", default=DATASETS)
    args = parser.parse_args()

    base       = Path(args.base).expanduser()
    results_v2 = base / "results_v2"

    if not base.exists():
        sys.exit(f"ERROR: Base directory not found: {base}")

    all_results = {}
    for ds in args.datasets:
        print(f"\n[{ds}] Analysing …")
        all_results[ds] = analyse_dataset(base, ds, results_v2)

    write_outputs(base, results_v2, all_results)
    print("\nDone. Results in:", results_v2 / "analysis" / "coverage")


if __name__ == "__main__":
    main()